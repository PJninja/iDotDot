/**
 * Create an ElementRegistry with every element type registered.
 * Type 0 is Air (reserved); all element types must be registered here.
 */
export function createElementRegistry(): ElementRegistry {
  const registry = new ElementRegistry();
  registry.register(new Air());
  registry.register(new Sand());
  registry.register(new Dirt());
  registry.register(new Smoke());
  registry.register(new Water());
  registry.register(new Steam());
  registry.register(new Wood());
  registry.register(new WetSand());
  registry.register(new Mud());
  registry.register(new Ember());
  registry.register(new Flame());
  registry.register(new Spark());
  registry.register(new Explosion());
  registry.register(new Bomb());
  registry.register(new Charcoal());
  registry.register(new Stone());
  registry.register(new Grass());
  registry.register(new Steel());
  registry.register(new HotSteel());
  registry.register(new CoolingSteel());
  registry.register(new Acid());
  registry.register(new Ice());
  registry.register(new Methane());
  registry.register(new Mold());
  registry.register(new Ash());
  registry.register(new Rubble());
  registry.register(new Spring());
  registry.register(new Torch());
  registry.register(new LiveSteel());
  registry.register(new SpentSteel());
  registry.register(new Arc());
  registry.register(new Generator());
  registry.register(new ShockedWater());
  registry.register(new NumbWater());
  registry.register(new Fuse());
  registry.register(new LiveFuse());
  registry.register(new Rubber());
  registry.register(new Copper());
  registry.register(new LiveCopper());
  registry.register(new SpentCopper());
  registry.register(new Bark());
  registry.register(new CharredBark());
  registry.register(new Debris());
  registry.register(new Scorch());
  registry.register(new Leaves());
  registry.register(new PoweredTorch());
  registry.register(new LitTorchA());
  registry.register(new LitTorchB());
  registry.register(new PoweredSpring());
  registry.register(new LitSpringA());
  registry.register(new LitSpringB());
  registry.register(new Oil());
  registry.register(new Void());
  return registry;
}
